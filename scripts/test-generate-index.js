// --- 3. --finalize rejects each bad map, and leaves no temp file -----------------
console.log('\n3. --finalize rejects each bad map');
// Each case starts with an earlier map and a legacy INDEX.md in place: a failed
// run must leave both exactly as they were.
function rejects(label, content, expectedError) {
  const dir = fresh('bad-' + label);
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md'), OLD_MAP);
  fs.writeFileSync(path.join(dir, 'INDEX.md'), OLD_INDEX);
  if (content !== null) fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), content);
  const r = finalize(dir);
  const j = r.json || {};
  check(label + ': exits non-zero with finalized false and a reason', r.status !== 0 && j.finalized === false && typeof j.reason === 'string' && j.reason.length > 0, r.stdout + r.stderr);
  check(label + ': error code ' + expectedError, j.error === expectedError, r.stdout);
  check(label + ': no temp file is left', !exists(dir, 'CODEBASE_MAP.md.tmp'));
  check(label + ': the earlier map and INDEX.md are untouched', read(dir, 'CODEBASE_MAP.md') === OLD_MAP && read(dir, 'INDEX.md') === OLD_INDEX);
}
const withoutLine = (text, line) => text.split('\n').filter((l) => l !== line).join('\n');
rejects('too small', '<!-- Generated: 2026-09-14 17:26 UTC -->\n\n# Codebase Map\n\n## Module Guide\n', 'too_small');
{
  // Exactly 200 bytes is still too small: the rule is over 200.
  const head = '<!-- Generated: 2026-09-14 17:26 UTC -->\n# Codebase Map\n## Module Guide\n';
  const at200 = head + 'x'.repeat(200 - Buffer.byteLength(head) - 1) + '\n';
  check('the boundary fixture is exactly 200 bytes', Buffer.byteLength(at200) === 200, String(Buffer.byteLength(at200)));
  rejects('exactly 200 bytes', at200, 'too_small');
}
rejects('wrong first line', '\n' + GOOD_MAP, 'no_generated_header');
rejects('Generated header line removed (the Commit comment comes first)', withoutLine(GOOD_MAP, '<!-- Generated: 2026-09-14 17:26 UTC -->'), 'no_generated_header');
rejects('missing # Codebase Map heading', withoutLine(GOOD_MAP, '# Codebase Map'), 'no_title');
rejects('a near-miss heading (# Codebase Map v2)', GOOD_MAP.replace('# Codebase Map\n', '# Codebase Map v2\n'), 'no_title');
rejects('missing ## Module Guide on a non-minimal map', withoutLine(GOOD_MAP, '## Module Guide'), 'no_module_guide');
rejects('a Files: 0 line quoted in the body does not waive the Module Guide', withoutLine(GOOD_MAP, '## Module Guide') + '\n<!-- Files: 0, Skipped: 0, Tokens: 0 -->\n', 'no_module_guide');
rejects('no temp file at all', null, 'no_temp_map');
{
  const dir = fresh('tmp-is-folder');
  fs.mkdirSync(path.join(dir, 'CODEBASE_MAP.md.tmp'));
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md'), OLD_MAP);
  const r = finalize(dir);
  const stillFolder = exists(dir, 'CODEBASE_MAP.md.tmp') && fs.statSync(path.join(dir, 'CODEBASE_MAP.md.tmp')).isDirectory();
  check('a folder named CODEBASE_MAP.md.tmp is refused, not moved over the map, and not deleted', r.status !== 0 && (r.json || {}).error === 'not_a_file' && read(dir, 'CODEBASE_MAP.md') === OLD_MAP && stillFolder, r.stdout);
}

