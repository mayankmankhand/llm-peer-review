  check('the result says finalized, names the map, and gives its size', j.finalized === true && j.map === 'CODEBASE_MAP.md' && j.bytes === Buffer.byteLength(GOOD_MAP) && j.tokens === Math.ceil(Buffer.byteLength(GOOD_MAP) / 4), r.stdout);
