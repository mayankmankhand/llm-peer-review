#!/usr/bin/env node
'use strict';
// test-generate-index.js - assertions for .claude/scripts/generate-index.js:
// --finalize (issue #181), the one call /index makes to check
// CODEBASE_MAP.md.tmp, rename it over CODEBASE_MAP.md and remove the legacy
// INDEX.md, in place of a shell compound that default permission mode stops to
// ask about; and the scan's `git ls-files -z` (issue #183), which keeps files
// with non-ASCII names in the manifest instead of counting them as missing.
// Every case runs in a throwaway folder under the OS temp dir. The scan cases
// build scratch git repos that read no global or system git config, so a
// developer's own settings (core.quotePath, an excludes file) cannot change
// what the scan sees. Dependency-free; exits non-zero on any failure.
//
//   node scripts/test-generate-index.js

const { execFileSync, spawnSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const SCRIPT = path.resolve(__dirname, '..', '.claude', 'scripts', 'generate-index.js');

// Process-wide, so the suite's own git calls and the scanner's inherit it.
process.env.GIT_CONFIG_GLOBAL = os.devNull;
process.env.GIT_CONFIG_NOSYSTEM = '1';

let passed = 0;
const failures = [];
function check(name, cond, detail) {
  if (cond) { passed++; console.log('  ok  ' + name); }
  else { failures.push(name + (detail ? ' - ' + detail : '')); console.log('  FAIL ' + name + (detail ? ' - ' + String(detail).slice(0, 300) : '')); }
}

const sandbox = fs.mkdtempSync(path.join(os.tmpdir(), 'generate-index-'));
let counter = 0;
function fresh(label) {
  const dir = path.join(sandbox, label + '-' + (++counter));
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}
const exists = (dir, rel) => fs.existsSync(path.join(dir, rel));
// null for a missing file, so a check fails and counts instead of throwing.
function read(dir, rel) {
  try { return fs.readFileSync(path.join(dir, rel), 'utf8'); } catch (e) { return null; }
}

// Run the script in a folder. json is the parsed stdout when stdout is exactly
// one JSON object, else null.
function run(dir, args, extraEnv) {
  const r = spawnSync(process.execPath, [SCRIPT, ...args], {
    cwd: dir, encoding: 'utf8', env: Object.assign({}, process.env, extraEnv || {}),
  });
  let json = null;
  try { json = JSON.parse(r.stdout); } catch (e) { json = null; }
  return { status: r.status, stdout: r.stdout, stderr: r.stderr, json };
}
const finalize = (dir) => run(dir, ['--finalize']);

// A map in the shape /index step 4 writes.
const GOOD_MAP = [
  '<!-- Generated: 2026-09-14 17:26 UTC -->',
  '<!-- Commit: 1e84a200cb7b14047f34a99a36c14a41dcb6bc95 -->',
  '<!-- Files: 3, Skipped: 0, Tokens: 1200 -->',
  '',
  '# Codebase Map',
  '',
  '> Semantic map generated by `/index`, refreshed by `/document`.',
  '> If HEAD has moved since the commit above, this map may be stale - run `/index` to refresh.',
  '',
  '## System Overview',
  'A small fixture project with one module.',
  '',
  '## Directory Tree',
  '- src/',
  '  - app.js',
  '',
  '## Module Guide',
  '',
  '### src/app.js',
  '**Purpose:** The fixture\'s only module.',
  '',
].join('\n');

// The empty-repo minimal map: the same header with the scan's zero counts, the
// no-files note, and no Module Guide.
const MINIMAL_MAP = [
  '<!-- Generated: 2026-09-14 17:26 UTC -->',
  '<!-- Commit: (no commits yet) -->',
  '<!-- Files: 0, Skipped: 0, Tokens: 0 -->',
  '',
  '# Codebase Map',
  '',
  '> Semantic map generated by `/index`, refreshed by `/document`.',
  '> If HEAD has moved since the commit above, this map may be stale - run `/index` to refresh.',
  '',
  'No tracked files yet. Commit some files and run `/index` to regenerate.',
  '',
].join('\n');

const OLD_MAP = '<!-- Generated: 2026-01-01 00:00 UTC -->\n# Codebase Map\nthe previous map\n';
const OLD_INDEX = '# Index\n- the old flat tree\n';

// --- 1. --finalize accepts a good map ------------------------------------------
console.log('\n1. --finalize accepts a good map');
{
  const dir = fresh('good');
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), GOOD_MAP);
  const r = finalize(dir);
  const j = r.json || {};
  check('a good map exits 0', r.status === 0, r.stdout + r.stderr);
  check('stdout is exactly one JSON object on one line', r.json !== null && r.stdout.trim().split('\n').length === 1, r.stdout);
  check('the result says finalized, names the map, and gives its size', j.finalized === true && j.map === 'CODEBASE_MAP.md' && j.bytes === Buffer.byteLength(GOOD_MAP) && j.tokens === Math.ceil(Buffer.byteLength(GOOD_MAP) / 4), r.stdout);
  check('CODEBASE_MAP.md holds the temp file\'s bytes', exists(dir, 'CODEBASE_MAP.md') && read(dir, 'CODEBASE_MAP.md') === GOOD_MAP);
  check('no temp file is left', !exists(dir, 'CODEBASE_MAP.md.tmp'));
  check('with no earlier map and no INDEX.md: not minimal, nothing replaced, nothing removed', j.minimal === false && j.replaced === false && j.indexRemoved === false, r.stdout);
}
{
  const dir = fresh('replace');
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md'), OLD_MAP);
  fs.writeFileSync(path.join(dir, 'INDEX.md'), OLD_INDEX);
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), GOOD_MAP);
  const r = finalize(dir);
  const j = r.json || {};
  check('over an earlier map and a legacy INDEX.md: exits 0 and says both', r.status === 0 && j.finalized === true && j.replaced === true && j.indexRemoved === true, r.stdout + r.stderr);
  check('the earlier map is replaced by the new one', read(dir, 'CODEBASE_MAP.md') === GOOD_MAP);
  check('the legacy INDEX.md is removed once the map is in place', !exists(dir, 'INDEX.md'));
  check('no temp file is left after a replace', !exists(dir, 'CODEBASE_MAP.md.tmp'));
}
{
  // Only the exact name INDEX.md is the legacy index. On a case-insensitive
  // filesystem a lookup of INDEX.md also finds index.md; this pins the rule.
  const dir = fresh('own-index');
  fs.writeFileSync(path.join(dir, 'index.md'), '# Our docs home page\n');
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), GOOD_MAP);
  const r = finalize(dir);
  check('a project\'s own lowercase index.md is kept', r.status === 0 && (r.json || {}).indexRemoved === false && fs.readdirSync(dir).includes('index.md') && read(dir, 'index.md') === '# Our docs home page\n', r.stdout + ' ' + fs.readdirSync(dir).join(','));
}
{
  const dir = fresh('crlf');
  const crlf = GOOD_MAP.replace(/\n/g, '\r\n');
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), crlf);
  const r = finalize(dir);
  check('a map written with CRLF line endings is accepted byte for byte', r.status === 0 && (r.json || {}).finalized === true && read(dir, 'CODEBASE_MAP.md') === crlf, r.stdout + r.stderr);
}

// --- 2. --finalize accepts the empty-repo minimal map ----------------------------
console.log('\n2. --finalize accepts the empty-repo minimal map');
{
  const dir = fresh('minimal');
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), MINIMAL_MAP);
  const r = finalize(dir);
  const j = r.json || {};
  check('the minimal map (Files: 0 header, no Module Guide) exits 0', r.status === 0 && j.finalized === true, r.stdout + r.stderr);
  check('the result marks it minimal', j.minimal === true, r.stdout);
  check('CODEBASE_MAP.md holds the minimal map and no temp file is left', read(dir, 'CODEBASE_MAP.md') === MINIMAL_MAP && !exists(dir, 'CODEBASE_MAP.md.tmp'));
  check('the minimal map is over the 200-byte floor as written', Buffer.byteLength(MINIMAL_MAP) > 200, String(Buffer.byteLength(MINIMAL_MAP)));
}

// --- 3. --finalize rejects each bad map, and leaves no temp file -----------------
console.log('\n3. --finalize rejects each bad map');
// Each case starts with an earlier map and a legacy INDEX.md in place: a failed
// run must leave both exactly as they were.
function rejects(label, content, expectedError) {
  const dir = fresh('bad-' + label);
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md'), OLD_MAP);
  fs.writeFileSync(path.join(dir, 'INDEX.md'), OLD_INDEX);
  if (content !== null) fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), content);
  const r = finalize(dir);
  const j = r.json || {};
  check(label + ': exits non-zero with finalized false and a reason', r.status !== 0 && j.finalized === false && typeof j.reason === 'string' && j.reason.length > 0, r.stdout + r.stderr);
  check(label + ': error code ' + expectedError, j.error === expectedError, r.stdout);
  check(label + ': no temp file is left', !exists(dir, 'CODEBASE_MAP.md.tmp'));
  check(label + ': the earlier map and INDEX.md are untouched', read(dir, 'CODEBASE_MAP.md') === OLD_MAP && read(dir, 'INDEX.md') === OLD_INDEX);
}
const withoutLine = (text, line) => text.split('\n').filter((l) => l !== line).join('\n');
rejects('too small', '<!-- Generated: 2026-09-14 17:26 UTC -->\n\n# Codebase Map\n\n## Module Guide\n', 'too_small');
{
  // Exactly 200 bytes is still too small: the rule is over 200.
  const head = '<!-- Generated: 2026-09-14 17:26 UTC -->\n# Codebase Map\n## Module Guide\n';
  const at200 = head + 'x'.repeat(200 - Buffer.byteLength(head) - 1) + '\n';
  check('the boundary fixture is exactly 200 bytes', Buffer.byteLength(at200) === 200, String(Buffer.byteLength(at200)));
  rejects('exactly 200 bytes', at200, 'too_small');
}
rejects('wrong first line', '\n' + GOOD_MAP, 'no_generated_header');
rejects('Generated header line removed (the Commit comment comes first)', withoutLine(GOOD_MAP, '<!-- Generated: 2026-09-14 17:26 UTC -->'), 'no_generated_header');
rejects('missing # Codebase Map heading', withoutLine(GOOD_MAP, '# Codebase Map'), 'no_title');
rejects('a near-miss heading (# Codebase Map v2)', GOOD_MAP.replace('# Codebase Map\n', '# Codebase Map v2\n'), 'no_title');
rejects('missing ## Module Guide on a non-minimal map', withoutLine(GOOD_MAP, '## Module Guide'), 'no_module_guide');
rejects('a Files: 0 line quoted in the body does not waive the Module Guide', withoutLine(GOOD_MAP, '## Module Guide') + '\n<!-- Files: 0, Skipped: 0, Tokens: 0 -->\n', 'no_module_guide');
rejects('no temp file at all', null, 'no_temp_map');
{
  const dir = fresh('tmp-is-folder');
  fs.mkdirSync(path.join(dir, 'CODEBASE_MAP.md.tmp'));
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md'), OLD_MAP);
  const r = finalize(dir);
  const stillFolder = exists(dir, 'CODEBASE_MAP.md.tmp') && fs.statSync(path.join(dir, 'CODEBASE_MAP.md.tmp')).isDirectory();
  check('a folder named CODEBASE_MAP.md.tmp is refused, not moved over the map, and not deleted', r.status !== 0 && (r.json || {}).error === 'not_a_file' && read(dir, 'CODEBASE_MAP.md') === OLD_MAP && stillFolder, r.stdout);
}

// --- 4. Arguments ----------------------------------------------------------------
console.log('\n4. arguments');
{
  const dir = fresh('bad-args');
  fs.writeFileSync(path.join(dir, 'CODEBASE_MAP.md.tmp'), GOOD_MAP);
  const typo = run(dir, ['--finalise']);
  check('a mistyped flag exits non-zero with a bad_arguments error and no manifest', typo.status !== 0 && (typo.json || {}).error === 'bad_arguments' && !/"chunks"/.test(typo.stdout), typo.stdout + typo.stderr);
  const extra = run(dir, ['--finalize', '--force']);
  check('--finalize with anything after it is refused the same way', extra.status !== 0 && (extra.json || {}).error === 'bad_arguments', extra.stdout);
  check('a refused call leaves the temp file alone and writes no map', exists(dir, 'CODEBASE_MAP.md.tmp') && !exists(dir, 'CODEBASE_MAP.md'));
}

// --- 5. The scan counts files with non-ASCII names --------------------------------
console.log('\n5. the scan counts files with non-ASCII names (git ls-files -z)');
function git(repo, args) { return execFileSync('git', args, { cwd: repo, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }); }
function initRepo(repo) {
  git(repo, ['init', '-q']);
  git(repo, ['config', 'user.email', 't@example.com']);
  git(repo, ['config', 'user.name', 'Test']);
  git(repo, ['config', 'commit.gpgsign', 'false']);
}
{
  const repo = fresh('scan');
  initRepo(repo);
  const names = ['README.md', 'docs/café.md', 'notes/日本語.md'];
  for (const n of names) {
    fs.mkdirSync(path.dirname(path.join(repo, n)), { recursive: true });
    fs.writeFileSync(path.join(repo, n), '# ' + n + '\n\nSome text so the file has a size.\n');
  }
  git(repo, ['add', '-A']);
  git(repo, ['commit', '-qm', 'init']);
  // The fixture only proves something while git quotes these names by default.
  const quoted = git(repo, ['ls-files']);
  check('fixture: plain git ls-files C-quotes the non-ASCII names here', quoted.includes('"docs/caf\\303\\251.md"'), quoted);
  const r = run(repo, []);
  const m = r.json || {};
  const listed = (m.chunks || []).flatMap((c) => c.files.map((f) => f.path)).sort();
  check('the scan exits 0 with a manifest', r.status === 0 && Array.isArray(m.chunks), r.stdout.slice(0, 300) + r.stderr);
  check('every tracked file is counted (totalFiles 3)', m.totalFiles === 3, 'totalFiles ' + m.totalFiles);
  check('no file is skipped as missing', m.skipCounts && m.skipCounts.missing === 0, JSON.stringify(m.skipCounts));
  check('the chunks carry each name verbatim', JSON.stringify(listed) === JSON.stringify(names.slice().sort()), JSON.stringify(listed));
  check('the directory tree shows the non-ASCII names', (m.directoryTree || []).includes('  - café.md') && (m.directoryTree || []).includes('  - 日本語.md'), JSON.stringify(m.directoryTree));
  check('the manifest records the commit and a clean tree', /^[0-9a-f]{40}$/.test(m.commit || '') && m.isDirty === false, (m.commit || '') + ' ' + m.isDirty);
}
{
  const repo = fresh('empty-repo');
  initRepo(repo);
  const r = run(repo, []);
  const m = r.json || {};
  check('an empty repo scans to zero files, no chunks and the no-commit placeholder', r.status === 0 && m.totalFiles === 0 && Array.isArray(m.chunks) && m.chunks.length === 0 && m.commit === '(no commits yet)', r.stdout.slice(0, 300));
}
{
  // GIT_CEILING_DIRECTORIES stops git from finding a repository above the
  // sandbox, in case the temp folder itself sits inside one.
  const dir = fresh('not-a-repo');
  const r = run(dir, [], { GIT_CEILING_DIRECTORIES: sandbox });
  check('outside a git repository the scan prints the git_failed error', r.status !== 0 && (r.json || {}).error === 'git_failed', r.stdout + r.stderr);
}

fs.rmSync(sandbox, { recursive: true, force: true });
console.log('');
if (failures.length === 0) { console.log(passed + ' checks passed.\n'); process.exit(0); }
console.log(failures.length + ' FAILED, ' + passed + ' passed:');
failures.forEach((f) => console.log('  - ' + f));
process.exit(1);
