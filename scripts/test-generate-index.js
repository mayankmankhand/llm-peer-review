#!/usr/bin/env node
'use strict';
// test-generate-index.js - assertions for .claude/scripts/generate-index.js:
// --finalize (issue #181), the one call /index makes to check
// CODEBASE_MAP.md.tmp, rename it over CODEBASE_MAP.md and remove the legacy
// INDEX.md, in place of a shell compound that default permission mode stops to
// ask about; and the scan's `git ls-files -z` (issue #183), which keeps files
// with non-ASCII names in the manifest instead of counting them as missing;
// and the manifest's overflowChunkIds (issue #226), the oversized chunks /index
// must not auto-retry. Every case runs in a throwaway folder under the OS temp dir. The scan cases
// build scratch git repos that read no global or system git config, so a
// developer's own settings (core.quotePath, an excludes file) cannot change
// what the scan sees. Dependency-free; exits non-zero on any failure.
//
//   node scripts/test-generate-index.js

const { execFileSync, spawnSync } = require('child_process');
const fs = require('fs');
const os = require('os');
const path = require('path');

const SCRIPT = path.resolve(__dirname, '..', '.claude', 'scripts', 'generate-index.js');

// Process-wide, so the suite's own git calls and the scanner's inherit it.
process.env.GIT_CONFIG_GLOBAL = os.devNull;
process.env.GIT_CONFIG_NOSYSTEM = '1';

let passed = 0;
const failures = [];
function check(name, cond, detail) {
  if (cond) { passed++; console.log('  ok  ' + name); }
  else { failures.push(name + (detail ? ' - ' + detail : '')); console.log('  FAIL ' + name + (detail ? ' - ' + String(detail).slice(0, 300) : '')); }
}

const sandbox = fs.mkdtempSync(path.join(os.tmpdir(), 'generate-index-'));
let counter = 0;
function fresh(label) {
  const dir = path.join(sandbox, label + '-' + (++counter));
  fs.mkdirSync(dir, { recursive: true });
  return dir;
}
const exists = (dir, rel) => fs.existsSync(path.join(dir, rel));
// null for a missing file, so a check fails and counts instead of throwing.
function read(dir, rel) {
  try { return fs.readFileSync(path.join(dir, rel), 'utf8'); } catch (e) { return null; }
}

// Run the script in a folder. json is the parsed stdout when stdout is exactly
// one JSON object, else null.
function run(dir, args, extraEnv) {
  const r = spawnSync(process.execPath, [SCRIPT, ...args], {
    cwd: dir, encoding: 'utf8', env: Object.assign({}, process.env, extraEnv || {}),
  });
  let json = null;
  try { json = JSON.parse(r.stdout); } catch (e) { json = null; }
  return { status: r.status, stdout: r.stdout, stderr: r.stderr, json };
}
const finalize = (dir) => run(dir, ['--finalize']);

